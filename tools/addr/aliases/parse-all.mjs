/**
 * Runs every parser against a raw-download root and rewrites `sources/*.tsv`, sorted, so that a
 * refresh shows as a reviewable git diff. The raw folders are read, never executed, and are not in
 * this repo.
 *
 *   node tools/addr/aliases/parse-all.mjs <raw root> [--only=osm,rada]
 *
 * <raw root> holds one folder per source, as the fetchers wrote them (see README.md).
 */
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeTsv } from './tsv.mjs';
import { SOURCE_COLUMNS } from './rows.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));

const CC_BY_SA = 'Wikipedia contributors, CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/); the revision of each page is the oldid in the url column.';
const ODBL = 'OpenStreetMap contributors, ODbL 1.0 (https://opendatacommons.org/licenses/odbl/); the way of each row is in the url column.';
const ACTS = 'Official acts (Verkhovna Rada, councils, regional administration); not objects of copyright (Copyright Act, art. 10).';

/** file → { module, dir (under the raw root; the councils and PDFs take the root itself), note } */
export const SOURCES = [
  { file: 'wikipedia-kyiv', module: './parse-wikipedia-kyiv.mjs', dir: 'wikipedia-kyiv', note: `uk.wikipedia «Список вулиць Києва». ${CC_BY_SA}` },
  { file: 'wikipedia-cities', module: './parse-wikipedia-cities.mjs', dir: 'wikipedia-uk-other', note: `uk.wikipedia street lists of Dnipro, Kryvyi Rih, Nikopol, Pavlohrad, Odesa, Boryspil, Khmelnytskyi, Vasylkiv. ${CC_BY_SA}` },
  { file: 'wikipedia-settlements', module: './parse-wikipedia-settlements.mjs', dir: 'wikipedia-uk-other', note: `uk.wikipedia lists of settlements renamed by the decommunisation and decolonisation laws. ${CC_BY_SA}` },
  { file: 'wikipedia-ru-odesa', module: './parse-wikipedia-ru-odesa.mjs', dir: 'wikipedia-ru-odesa', note: `ru.wikipedia «Список улиц Одессы»; Russian names, flag ruonly: they only give the Russian form of a pair known from elsewhere. ${CC_BY_SA}` },
  { file: 'osm', module: './parse-osm.mjs', dir: 'osm', note: `OpenStreetMap old_name tags, through Overpass. ${ODBL}` },
  { file: 'rada', module: './parse-rada.mjs', dir: 'rada', note: `Resolutions of the Verkhovna Rada on renaming settlements (zakon.rada.gov.ua). ${ACTS}` },
  { file: 'councils', module: './parse-councils.mjs', root: true, note: `Decisions of the councils of Boryspil, Bila Tserkva, Brovary and Khmelnytskyi. ${ACTS}` },
  { file: 'councils-pdf', module: './parse-pdfs.mjs', root: true, note: `Order 830/А-2024 of the Odesa regional administration and the street list of the Bucha hromada. ${ACTS}` },
  { file: 'rename-dp', module: './parse-rename-dp.mjs', dir: 'rename-dp', note: 'rename.dp.ua. NO LICENCE STATED: a cross-check only (code rdp); no published row may rest on it alone.' }
];

export async function parseAll(rawRoot, { only = null, outDir = join(HERE, 'sources'), log = () => {} } = {}) {
  const counts = {};
  for (const source of SOURCES) {
    if (only && !only.includes(source.file)) continue;
    const { parseRaw } = await import(source.module);
    const rows = await parseRaw(source.root ? rawRoot : join(rawRoot, source.dir));
    await writeTsv(join(outDir, `${source.file}.tsv`), SOURCE_COLUMNS, rows, `${source.note}\nGenerated by tools/addr/aliases/parse-all.mjs from the raw downloads; do not edit by hand (use manual/).`);
    counts[source.file] = rows.length;
    log(`${source.file.padEnd(24)} ${String(rows.length).padStart(6)} rows`);
  }
  return counts;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const root = args.find((a) => !a.startsWith('--'));
  const only = args.find((a) => a.startsWith('--only='))?.slice(7).split(',') ?? null;
  if (!root) { console.error('usage: parse-all.mjs <raw root> [--only=a,b]'); process.exit(1); }
  await parseAll(root, { only, log: (l) => console.error(l) });
}
